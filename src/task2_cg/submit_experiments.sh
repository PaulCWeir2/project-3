echo "  Task 5: Fine-tuned 100% data, rank 4 (~12 hours)"
echo "  Task 6: Fine-tuned 100% data, rank 16 (~12 hours)"
echo "  Task 7: Fine-tuned 100% data, rank 32 (~12 hours)"
echo ""
echo "=========================================="
echo "Monitoring Commands:"
echo "=========================================="
echo ""
echo "Check job status:"
echo "  squeue -u \$USER"
echo ""
echo "View specific experiment log:"
echo "  tail -f logs/task2_exp_${JOB_ID}_1.out  # Experiment 1"
echo "  tail -f logs/task2_exp_${JOB_ID}_2.out  # Experiment 2"
echo "  # etc..."
echo ""
echo "Check all logs at once:"
echo "  tail -f logs/task2_exp_${JOB_ID}_*.out"
echo ""
