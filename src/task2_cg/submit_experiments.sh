#!/bin/bash
# submit_experiments.sh
# Simple wrapper to submit the array job

echo "=========================================="
echo "Submitting Task 2: All 7 Experiments"
echo "=========================================="
echo ""

# Create necessary directories
mkdir -p logs
mkdir -p task2_outputs

# Make the array script executable
chmod +x run_experiments_array.sh

# Submit the array job (all 7 experiments)
echo "Submitting SLURM array job..."
JOB_ID=$(sbatch --parsable run_experiments_array.sh)

echo ""
echo "✓ Job submitted successfully!"
echo ""
echo "Job ID: ${JOB_ID}"
echo "Array tasks: 1-7 (7 experiments)"
echo ""
echo "=========================================="
